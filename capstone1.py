    _traffic_map = {'low': 0, 'average': 1, 'medium': 1, 'high': 2}
    df['TrafficLevel'] = (df['TrafficConditionNearby'].astype(str).str.strip().str.lower()
                          .map(_traffic_map).fillna(1).astype(int))
